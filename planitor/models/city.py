class Minute(Base):
    __tablename__ = "minutes"

    id = Column(Integer, primary_key=True, index=True)
    serial = Column(String, index=True)
    case_id = Column(Integer, ForeignKey(Case.id), nullable=True, index=True)
    case = relationship(Case)
    status = Column(Enum(CaseStatusEnum), nullable=True)
    meeting_id = Column(Integer, ForeignKey(Meeting.id), nullable=True, index=True)
    meeting = relationship(Meeting)
    headline = Column(String, nullable=False)
    inquiry = Column(String)
    remarks = Column(String)
    lemmas = Column(String)
    search_vector = Column(TSVectorType(regconfig="pg_catalog.simple"))
    subcategory = Column(String)
    participants = Column(String)
    entrants_and_leavers = Column(ARRAY(String))
    responses = relationship(Response, order_by="Response.order")
    stadgreinir = Column(String)

    attachments = relationship(Attachment)

    entity_mention_rows = relationship(
        MinuteEntityMention,
        back_populates="minute",
        cascade="all, delete-orphan",
        order_by=(MinuteEntityMention.start, MinuteEntityMention.end),
    )

    __table_args__ = (
        Index("ix_search_vector_tsv", search_vector, postgresql_using="gin"),
    )

    def __repr__(self):
        return f"<Minute id={self.id} serial={self.serial}>"

    @property
    def entity_mentions(self):
        return [mention.as_tuple() for mention in self.entity_mention_rows]

    @entity_mentions.setter
    def entity_mentions(self, mentions):
        self.entity_mention_rows = [
            MinuteEntityMention(entity_id=kennitala, start=start, end=end)
            for kennitala, start, end in (mentions or [])
        ]

    def assign_entity_mentions(self, mentions):
        entity_mentions = []
        for kennitala, locations in mentions.items():
            for location in locations:
                start, end = location
                entity_mentions.append((kennitala, start, end))
        self.entity_mentions = entity_mentions

    def get_inquiry_mention_tokens(self):
        """Use `entity_mentions` to mark linkable locations in the `inquiry` text"""
        s = self.inquiry
        entity_mentions = list(self.entity_mentions)
        mentions = sorted(entity_mentions, key=lambda i: i[1])

        if not mentions:
            yield (None, s)

        def tokens():

            for i, (kennitala, start, end) in enumerate(mentions):
                if i == 0:
                    # Before first token
                    yield (None, s[0:start])

                # Token
                yield (Kennitala(kennitala), s[start:end])

                if len(mentions) != i + 1:
                    # Up to next token
                    next_start = mentions[i + 1][1]
                    yield (None, s[end:next_start])
                else:
                    # Or to end if this is last iteration
                    yield (None, s[end:])

        for category, text in tokens():
            if not text:
                continue
            yield (category, text)


